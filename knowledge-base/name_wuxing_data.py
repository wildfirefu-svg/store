def _get_sancai_judgment(tian, ren, di):
    """Judge a 三才 configuration based on 相生相克 relationships."""
    good_count = 0
    bad_count = 0
    details = []

    # 天→人
    if (tian, ren) in _WUXING_SHENG:
        good_count += 2
        details.append(f'天格{tian}生人格{ren}(吉)')
    elif (tian, ren) in _WUXING_KE:
        bad_count += 2
        details.append(f'天格{tian}克人格{ren}(凶)')
    elif tian == ren:
        good_count += 1
        details.append(f'天格{tian}同人格{ren}(平)')

    # 人→地
    if (ren, di) in _WUXING_SHENG:
        good_count += 2
        details.append(f'人格{ren}生地格{di}(吉)')
    elif (ren, di) in _WUXING_KE:
        bad_count += 2
        details.append(f'人格{ren}克地格{di}(凶)')
    elif ren == di:
        good_count += 1
        details.append(f'人格{ren}同地格{di}(平)')

    # 天→地 (lesser impact)
    if (tian, di) in _WUXING_SHENG:
        good_count += 1
        details.append(f'天格{tian}生地格{di}(吉)')
    elif (tian, di) in _WUXING_KE:
        bad_count += 1
        details.append(f'天格{tian}克地格{di}(凶)')

    # Judgment
    if good_count >= 4 and bad_count == 0:
        cat = 1  # 大吉
    elif good_count >= 3 and bad_count <= 1:
        cat = 2  # 吉
    elif good_count >= 2 and bad_count <= 2:
        cat = 3  # 平
    elif bad_count >= 3:
        cat = 4  # 凶
    else:
        cat = 3

    return cat, '；'.join(details)


