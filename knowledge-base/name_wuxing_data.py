def get_tone(c):
    """Get the tone (1-4) of a character, defaulting to 1 if unknown."""
    return _TONE_MAP.get(c, 1)


def analyze_phonetics(name_chars):
    """
    Analyze the phonetic quality of a name.
    Returns (score, notes).
    """
    if len(name_chars) < 2:
        return (7, '单名，音韵分析有限')

    score = 7  # baseline
    notes = []
    tones = [get_tone(c) for c in name_chars]

    # Rule 1: 平仄搭配 (alternating tones is better)
    if len(tones) >= 2:
        if tones[0] != tones[1]:
            score += 1
            notes.append('平仄相间')
        else:
            score -= 1
            notes.append('平仄相同→稍逊')

    # Rule 2: 避免同声母 too similar (crude check: same initial tone)
    if len(tones) >= 3 and tones[0] == tones[1] == tones[2]:
        score -= 1
        notes.append('三字同调→单调')

    # Rule 3: 第三声连读 (T3+T3 → first changes to T2 in Mandarin)
    if len(tones) >= 2 and tones[-2] == 3 and tones[-1] == 3:
        notes.append('两声三声连读→需变调')

    # Rule 4: 尾字声调 — 4声结尾有力, 1声结尾平稳
    if tones[-1] == 4:
        score += 1
        notes.append('尾字去声→响亮有力')
    elif tones[-1] == 1:
        notes.append('尾字阴平→平稳悠长')

    return (min(10, max(1, score)), '；'.join(notes) if notes else '音韵流畅')


